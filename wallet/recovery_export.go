var ErrRecoveryProfile = errors.New("wallet does not match the supported fixture recovery profile")

type recoveryCreation struct {
	public, private []byte
	manifest        recovery.Manifest
	candidate       *productionprofile.Manifest
}

func recoveryChain(params *chaincfg.Params) error {
	if wire.TestPoW || params == nil || params.GenesisHash == nil ||
		uint32(params.Net) != recovery.Network || params.GenesisHash.String() != recovery.Genesis {
		return ErrRecoveryProfile
	}
	return nil
}

func prepareRecovery(entropy [32]byte, manifest recovery.Manifest, params *chaincfg.Params) (*recoveryCreation, *hdkeychain.ExtendedKey, error) {
	defer zero.Bytes(entropy[:])
	if err := recoveryChain(params); err != nil {
		return nil, nil, err
	}
	if err := recovery.ValidateEntropyManifest(entropy, manifest); err != nil {
		return nil, nil, ErrRecoveryProfile
	}
	public, err := recovery.MarshalManifest(manifest)
	if err != nil {
		return nil, nil, ErrRecoveryProfile
	}
	seed := recovery.SeedFromEntropy(entropy)
	defer zero.Bytes(seed[:])
	root, err := hdkeychain.NewMaster(seed[:], params)
	if err != nil {
		return nil, nil, ErrRecoveryProfile
	}
	private := make([]byte, 68)
	binary.LittleEndian.PutUint32(private, recovery.Version1)
	copy(private[4:36], entropy[:])
	digest := sha256.Sum256(public)
	copy(private[36:], digest[:])
	return &recoveryCreation{public: public, private: private, manifest: manifest}, root, nil
}

// CreateNewRecoveryWallet creates only the explicitly labelled phase-A fixture
// profile. Entropy is supplied by the caller; no real keys are generated by this
// API's tests. Retention and wallet initialization commit in the same transaction.
// The caller must clear its entropy and passphrase copies when finished.
func (l *Loader) CreateNewRecoveryWallet(pubPassphrase, privPassphrase []byte,
	entropy [32]byte, birthday time.Time) (*Wallet, error) {
	defer zero.Bytes(entropy[:])
	manifest, err := recovery.ManifestFor(entropy, recovery.DefaultAccounts())
	if err != nil {
		return nil, ErrRecoveryProfile
	}
	data, root, err := prepareRecovery(entropy, manifest, l.chainParams)
	if err != nil {
		return nil, err
	}
	defer root.Zero()
	defer zero.Bytes(data.private)
	return l.createNewWallet(pubPassphrase, privPassphrase, root, birthday, false, data)
}

// RestoreRecoveryWallet restores into a new empty wallet from the exact export.
// It derives every advertised branch index before committing and starts scanning
// at genesis. It does not claim the asynchronous chain scan has completed.
func (l *Loader) RestoreRecoveryWallet(pubPassphrase, privPassphrase []byte,
	bundle recovery.Export) (*Wallet, error) {
	if len(bundle.Manifest.Accounts) != len(recovery.DefaultAccounts()) {
		return nil, ErrRecoveryProfile
	}
	bundle.Manifest.Accounts = append([]recovery.Account(nil), bundle.Manifest.Accounts...)
	if err := recoveryChain(l.chainParams); err != nil {
		return nil, err
	}
	if err := recovery.ValidateExport(bundle); err != nil {
		return nil, ErrRecoveryProfile
	}
	entropy, err := recovery.Entropy(bundle.Mnemonic)
	if err != nil {
		return nil, ErrRecoveryProfile
	}
	defer zero.Bytes(entropy[:])
	data, root, err := prepareRecovery(entropy, bundle.Manifest, l.chainParams)
	if err != nil {
		return nil, err
	}
	defer root.Zero()
	defer zero.Bytes(data.private)
	return l.createNewWallet(pubPassphrase, privPassphrase, root,
		l.chainParams.GenesisBlock.Header.Timestamp, false, data)
}

func restoreRecoveryCursors(ns walletdb.ReadWriteBucket, pubPass []byte, params *chaincfg.Params, manifest recovery.Manifest) error {
	mgr, err := waddrmgr.Open(ns, pubPass, params)
	if err != nil {
		return err
	}
	defer mgr.Close()
	for _, account := range manifest.Accounts {
		scope, err := mgr.FetchScopedKeyManager(waddrmgr.KeyScope{Purpose: account.Purpose, Coin: account.Coin})
		if err != nil {
			return ErrRecoveryProfile
		}
		if account.NextExternal > 0 {
			if err := scope.ExtendExternalAddresses(ns, 0, account.NextExternal-1); err != nil {
				return err
			}
		}
		if account.NextInternal > 0 {
			if err := scope.ExtendInternalAddresses(ns, 0, account.NextInternal-1); err != nil {
				return err
			}
		}
	}
	states, err := waddrmgr.RecoveryAccounts(ns)
	if err != nil {
		return err
	}
	for _, expected := range manifest.Accounts {
		found := false
		for _, state := range states {
			if state.Scope.Purpose == expected.Purpose && state.Scope.Coin == expected.Coin {
				found = state.NextExternal == expected.NextExternal && state.NextInternal == expected.NextInternal
			}
		}
		if !found {
			return ErrRecoveryProfile
		}
	}
	return nil
}

func readRecoveryBase(ns walletdb.ReadBucket, mgr *waddrmgr.Manager, params *chaincfg.Params) (recovery.Manifest, []byte, error) {
	var none recovery.Manifest
	if err := recoveryChain(params); err != nil {
		return none, nil, err
	}
	if !mgr.RecoveryEnabled() || mgr.RecoveryVersion() != recovery.Version1 {
		return none, nil, waddrmgr.ErrRecoveryUnavailable
	}
	if mgr.DerivationMode() != waddrmgr.DerivationStandard {
		return none, nil, waddrmgr.ErrRecoveryState
	}
	public, err := mgr.RecoveryData(ns, false)
	if err != nil {
		return none, nil, err
	}
	manifest, err := recovery.ParseManifest(public)
	if err != nil {
		return none, nil, waddrmgr.ErrRecoveryState
	}
	root, err := mgr.RecoveryRootPublicKey(ns)
	if err != nil || root != manifest.RootPublicKey {
		return none, nil, waddrmgr.ErrRecoveryState
	}
	return manifest, public, nil
}

func readRecoveryPublic(ns walletdb.ReadBucket, mgr *waddrmgr.Manager, params *chaincfg.Params) (recovery.Manifest, error) {
	manifest, _, err := readRecoveryBase(ns, mgr, params)
	if err != nil {
		return recovery.Manifest{}, err
	}
	states, err := waddrmgr.RecoveryAccounts(ns)
	if err != nil {
		return recovery.Manifest{}, err
	}
	accounts := recovery.DefaultAccounts()
	for i := range accounts {
		found := false
		for _, state := range states {
			if state.Scope.Purpose == accounts[i].Purpose && state.Scope.Coin == accounts[i].Coin {
				accounts[i].NextExternal, accounts[i].NextInternal = state.NextExternal, state.NextInternal
				found = true
			}
		}
		if !found {
			return recovery.Manifest{}, waddrmgr.ErrRecoveryInventory
		}
	}
	manifest.Accounts = accounts
	return manifest, nil
}

// recoveryPublicManifest contains no secrets and is available while locked.
// All cursor values come from one committed database snapshot, not live caches.
func (w *Wallet) recoveryPublicManifest() (recovery.Manifest, error) {
	var result recovery.Manifest
	err := walletdb.View(w.db, func(tx walletdb.ReadTx) error {
		var err error
		result, err = readRecoveryPublic(tx.ReadBucket(waddrmgrNamespaceKey), w.Manager, w.chainParams)
		return err
	})
	return result, err
}

// recoveryMaterial requires the caller to hold an unlocked lease. The returned
// entropy is caller-owned and must be zeroed. No node I/O/newAddrMtx is used.
func (w *Wallet) recoveryMaterial() (entropy [32]byte, manifest recovery.Manifest, err error) {
	defer func() {
		if err != nil {
			zero.Bytes(entropy[:])
			manifest = recovery.Manifest{}
		}
	}()
	err = walletdb.View(w.db, func(tx walletdb.ReadTx) error {
		ns := tx.ReadBucket(waddrmgrNamespaceKey)
		base, public, err := readRecoveryBase(ns, w.Manager, w.chainParams)
		if err != nil {
			return err
		}
		private, err := w.Manager.RecoveryData(ns, true)
		if err != nil {
			return err
		}
		defer zero.Bytes(private)
		digest := sha256.Sum256(public)
		if len(private) != 68 || binary.LittleEndian.Uint32(private) != recovery.Version1 || !bytes.Equal(private[36:], digest[:]) {
			return waddrmgr.ErrRecoveryState
		}
		copy(entropy[:], private[4:36])
		if err := recovery.ValidateEntropyManifest(entropy, base); err != nil {
			return waddrmgr.ErrRecoveryState
		}
		manifest, err = readRecoveryPublic(ns, w.Manager, w.chainParams)
		if err != nil {
			return err
		}
		return w.validateRecoveryAccountKeys(ns, entropy, manifest)
	})
	return
}

func (w *Wallet) validateRecoveryAccountKeys(ns walletdb.ReadBucket, entropy [32]byte, manifest recovery.Manifest) error {
	defer zero.Bytes(entropy[:])
	seed := recovery.SeedFromEntropy(entropy)
	defer zero.Bytes(seed[:])
	root, err := hdkeychain.NewMaster(seed[:], w.chainParams)
	if err != nil {
		return waddrmgr.ErrRecoveryState
	}
	defer root.Zero()
	for _, account := range manifest.Accounts {
		key := root
		for _, index := range []uint32{account.Purpose, account.Coin, 0} {
			next, err := key.Derive(index + hdkeychain.HardenedKeyStart)
			if key != root {
				key.Zero()
			}
			if err != nil {
				return waddrmgr.ErrRecoveryState
			}
			key = next
		}
		public, err := key.Neuter()
		if err != nil {
			key.Zero()
			return waddrmgr.ErrRecoveryState
		}
		// Neuter shares chain-code storage; serialize before clearing either key.
		want := public.String()
		public.Zero()
		key.Zero()
		scope, err := w.Manager.FetchScopedKeyManager(waddrmgr.KeyScope{Purpose: account.Purpose, Coin: account.Coin})
		if err != nil {
			return waddrmgr.ErrRecoveryState
		}
		properties, err := scope.AccountProperties(ns, 0)
		if err != nil || properties.AccountPubKey == nil || properties.AccountPubKey.String() != want {
			return waddrmgr.ErrRecoveryState
		}
	}
	return nil
}

// ExportRecovery reveals the approved 24-word phrase and complete supported
// metadata after explicit unlock. Returned strings are secret caller-owned data;
// Go memory clearing is best effort. No file, RPC, log, or webview output occurs.
func (w *Wallet) ExportRecovery(ctx context.Context) (recovery.Export, error) {
	lease, err := w.holdUnlockContext(ctx)
	if err != nil {
		return recovery.Export{}, err
	}
	defer lease.release()
	entropy, manifest, err := w.recoveryMaterial()
	defer zero.Bytes(entropy[:])
	if err != nil {
		return recovery.Export{}, err
	}
	result, err := recovery.NewExport(entropy, manifest.Accounts)
	if err != nil {
		return recovery.Export{}, ErrRecoveryProfile
	}
	if err := lease.err(ctx); err != nil {
		return recovery.Export{}, err
	}
	return result, nil
}
